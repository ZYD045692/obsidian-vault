def sec_files(sub):
    """节号 -> 文件名（无扩展名）"""
    out = {}
    for f in glob.glob(os.path.join(NOTE, sub, "小节", "*.md")):
        m = re.match(r"([\d.]+)-", os.path.basename(f))
        if m:
            out[m.group(1)] = os.path.basename(f)[:-3]
    return out

def insert_links(path, lines):
    """往 ## 关联 区追加行（幂等），返回新增数"""
    t = open(path, encoding="utf-8").read()
    m = re.search(r"(?ms)^## 关联\n(.*?)(?=^## |\Z)", t)
    if not m:
        print("!! 无关联区:", path); return 0
    body = m.group(1)
    add = [l for l in lines if l not in body]
    if not add:
        return 0
    newbody = body.rstrip("\n") + "\n" + "\n".join(add) + "\n\n"
    os.makedirs(BACKUP, exist_ok=True)
    bp = os.path.join(BACKUP, sub_of(path) + "__" + os.path.basename(path))
    if not os.path.exists(bp):
        shutil.copy2(path, bp)
    open(path, "w", encoding="utf-8", newline="\n").write(t[:m.start(1)] + newbody + t[m.end(1):])
    return len(add)

def sub_of(path):
    return "高数" if "高数" in path else "线代"

def main():
    total_edges = 0
    for sub, edges in [("高数", GS), ("线代", XD)]:
        files = sec_files(sub)
        # 校验目标
        for sec, es in edges.items():
            assert sec in files, f"{sub} {sec} 无文件"
            for tgt, rel, why in es:
                if tgt.startswith("Z"):
                    assert ZHUB[tgt], tgt
                else:
                    assert tgt in files, f"{sub} {tgt} 无文件"
        # 1) 语义边
        for sec, es in edges.items():
            lines = []
            for tgt, rel, why in es:
                name = ZHUB[tgt] if tgt.startswith("Z") else files[tgt]
                lines.append(f"- {rel}：[[{name}]]" + (f"（{why}）" if why else ""))
            n = insert_links(os.path.join(NOTE, sub, "小节", files[sec] + ".md"), lines)
            total_edges += n
        # 2) 机械讲内前后链（无语义边覆盖才补）
        lecs = {}
        for sec in files:
            lec = sec.split(".")[0]
            lecs.setdefault(lec, []).append(sec)
        for lec, secs in lecs.items():
            secs.sort(key=lambda s: int(s.split(".")[1]))
            for i, sec in enumerate(secs):
                path = os.path.join(NOTE, sub, "小节", files[sec] + ".md")
                body = open(path, encoding="utf-8").read()
                lines = []
                if i > 0 and files[secs[i-1]] not in body:
                    lines.append(f"- 前一节：[[{files[secs[i-1]]}]]")
                if i < len(secs) - 1 and files[secs[i+1]] not in body:
                    lines.append(f"- 后一节：[[{files[secs[i+1]]}]]")
                total_edges += insert_links(path, lines)
        # 3) 讲笔记下沉链
        lec_notes = {re.search(r"第(\d+)讲", os.path.basename(p)).group(1): p
                     for p in glob.glob(os.path.join(NOTE, f"30讲-{sub}", "*", "第*讲-*.md")) if "第0讲" not in p}
        for lec, secs in lecs.items():
            if lec not in lec_notes:
                continue
            secs.sort(key=lambda s: int(s.split(".")[1]))
            line = "- 本讲小节：" + "、".join(f"[[{files[s]}]]" for s in secs)
            insert_links(lec_notes[lec], [line])
    print(f"完成：新增语义+机械边 {total_edges} 条")

if __name__ == "__main__":
    main()
