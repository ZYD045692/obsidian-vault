def check_targets():
    """校验所有链接目标在库里存在"""
    import glob
    names = {os.path.basename(p)[:-3] for p in glob.glob("11408/notes/数学/**/*.md", recursive=True)}
    bad = []
    for path, lines in LINKS.items():
        for l in lines:
            for tgt in re.findall(r"\[\[([^\]|]+)", l):
                if tgt not in names:
                    bad.append((path, tgt))
    return bad

def main():
    bad = check_targets()
    if bad:
        for p, t in bad:
            print("链接目标不存在:", p, "->", t)
        sys.exit(1)
    changed = 0
    for path, lines in LINKS.items():
        t = open(path, encoding="utf-8").read()
        m = re.search(r"(?ms)^## 关联\n(.*?)(?=^## |\Z)", t)
        if not m:
            print("!! 无关联区:", path); continue
        body = m.group(1)
        add = [l for l in lines if l.split("：", 1)[-1] not in body and l not in body]
        if not add:
            print("== 已有，跳过:", os.path.basename(path)); continue
        newbody = body.rstrip("\n") + "\n" + "\n".join(add) + "\n\n"
        os.makedirs(BACKUP, exist_ok=True)
        bp = os.path.join(BACKUP, os.path.basename(path))
        if not os.path.exists(bp):
            shutil.copy2(path, bp)
        open(path, "w", encoding="utf-8", newline="\n").write(t[:m.start(1)] + newbody + t[m.end(1):])
        changed += 1
        print("✓", os.path.basename(path), f"+{len(add)} 条")
    print(f"完成：{changed}/{len(LINKS)} 篇写入")

if __name__ == "__main__":
    main()
